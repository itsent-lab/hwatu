CREATE COLLATION IF NOT EXISTS hwatu_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(40) COLLATE hwatu_ci NOT NULL,
    display_name VARCHAR(40) COLLATE hwatu_ci NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role varchar(16) NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
    is_active boolean NOT NULL DEFAULT true,
    auth_version integer NOT NULL DEFAULT 1 CHECK (auth_version >= 0),
    virtual_balance BIGINT NOT NULL DEFAULT 500000,
    opponent_balance BIGINT NOT NULL DEFAULT 500000,
    gostop_computer_a_balance BIGINT NOT NULL DEFAULT 500000,
    gostop_computer_b_balance BIGINT NOT NULL DEFAULT 500000,
    profile_image bytea NULL,
    profile_image_content_type VARCHAR(32) NULL,
    profile_image_updated_at timestamp(6) NULL,
    settings_json jsonb NULL,
    last_login_at timestamp(0) NULL,
    created_at timestamp(0) NOT NULL DEFAULT date_trunc('second', statement_timestamp()::timestamp),
    updated_at timestamp(0) NOT NULL DEFAULT date_trunc('second', statement_timestamp()::timestamp),
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS game_saves (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    slot_key VARCHAR(32) NOT NULL DEFAULT 'matgo-main',
    game_uuid uuid NOT NULL,
    game_mode varchar(16) NOT NULL DEFAULT 'matgo' CHECK (game_mode IN ('matgo', 'gostop')),
    status varchar(16) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'abandoned')),
    state_version integer NOT NULL DEFAULT 1 CHECK (state_version >= 0),
    turn_number integer NOT NULL DEFAULT 0 CHECK (turn_number >= 0),
    state_json jsonb NOT NULL,
    device_id VARCHAR(64) NULL,
    created_at timestamp(0) NOT NULL DEFAULT date_trunc('second', statement_timestamp()::timestamp),
    updated_at timestamp(0) NOT NULL DEFAULT date_trunc('second', statement_timestamp()::timestamp),
    PRIMARY KEY (id),
    CONSTRAINT game_saves_user_slot_unique UNIQUE (user_id, slot_key),
    CONSTRAINT game_saves_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS match_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    game_uuid uuid NOT NULL,
    game_mode varchar(16) NOT NULL DEFAULT 'matgo' CHECK (game_mode IN ('matgo', 'gostop')),
    result varchar(16) NOT NULL CHECK (result IN ('win', 'loss', 'draw', 'nagari')),
    final_score INT NOT NULL DEFAULT 0,
    settlement_amount BIGINT NOT NULL DEFAULT 0,
    balance_after BIGINT NOT NULL,
    opponent_balance_after BIGINT NOT NULL DEFAULT 500000,
    gostop_computer_a_balance_after BIGINT NOT NULL DEFAULT 500000,
    gostop_computer_b_balance_after BIGINT NOT NULL DEFAULT 500000,
    summary_json jsonb NULL,
    played_at timestamp(0) NOT NULL DEFAULT date_trunc('second', statement_timestamp()::timestamp),
    PRIMARY KEY (id),
    CONSTRAINT match_history_game_unique UNIQUE (user_id, game_uuid),
    CONSTRAINT match_history_user_fk
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique ON users (rtrim(username));
CREATE INDEX IF NOT EXISTS users_active_idx ON users (is_active);
CREATE INDEX IF NOT EXISTS game_saves_user_status_idx ON game_saves (user_id, status, updated_at);
CREATE INDEX IF NOT EXISTS match_history_user_date_idx ON match_history (user_id, played_at);

CREATE OR REPLACE FUNCTION hwatu_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := date_trunc('second', clock_timestamp()::timestamp);
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER users_touch_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION hwatu_touch_updated_at();
CREATE OR REPLACE TRIGGER game_saves_touch_updated_at BEFORE UPDATE ON game_saves
    FOR EACH ROW EXECUTE FUNCTION hwatu_touch_updated_at();
